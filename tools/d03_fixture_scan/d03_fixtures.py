# ---------------------------------------------------------------- primitives
def sha256_file(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(chunk), b""):
            h.update(b)
    return h.hexdigest()


def norm(s):
    return (s or "").strip().upper()


def isin_check_digit(body11):
    vals = []
    for ch in body11.upper():
        if ch.isdigit():
            vals.append(ch)
        elif "A" <= ch <= "Z":
            vals.append(str(ord(ch) - 55))
        else:
            return None
    digits, total, dbl = "".join(vals), 0, True
    for ch in reversed(digits):
        d = int(ch)
        if dbl:
            d *= 2
            if d > 9:
                d -= 9
        total += d
        dbl = not dbl
    return (10 - total % 10) % 10


def make_isin(body11):
    return body11 + str(isin_check_digit(body11))


def validate_isin(s):
    """-> category ∈ {BLANK, VALID, INVALID_LEN, INVALID_PREFIX, INVALID_CHARSET, INVALID_CHECKDIGIT}"""
    v = norm(s).replace(" ", "")
    if v == "":
        return "BLANK"
    if len(v) != 12:
        return "INVALID_LEN"
    if not v.startswith("IN"):
        return "INVALID_PREFIX"
    if not re.fullmatch(r"IN[A-Z0-9]{9}[0-9]", v):
        return "INVALID_CHARSET"
    return "VALID" if isin_check_digit(v[1:11]) == int(v[11]) else "INVALID_CHECKDIGIT"


def read_zip_text(zip_path):
    with zipfile.ZipFile(zip_path) as zf:
        data = zf.read(zf.namelist()[0])
    return data.decode("utf-8-sig", errors="replace")


def iter_rows(zip_path):
    """Yield (row_index, fields). row_index 0 = header."""
    for i, r in enumerate(csv.reader(io.StringIO(read_zip_text(zip_path)))):
        yield i, r


def header_index(zip_path):
    for i, r in iter_rows(zip_path):
        names = [h.strip() for h in r]
        return names, {n: j for j, n in enumerate(names) if n}
    raise ValueError("empty archive: " + zip_path)


def get(r, idx, col):
    j = idx.get(col)
    return r[j] if j is not None and j < len(r) else ""


def is_udiff_header(names):
    return "TckrSymb" in names and "SctySrs" in names


@dataclass
class Archive:
    kind: str
    path: str
    name: str
    date: str

    def key(self):
        return (self.date, self.kind, self.name)


def discover(legacy_root, udiff_root):
    out = []
    for kind, root in (("LEGACY", legacy_root), ("UDIFF", udiff_root)):
        if not root or not os.path.isdir(root):
            continue
        for dirpath, _dirs, names in os.walk(root):
            for nm in names:
                d = None
                if kind == "LEGACY":
                    m = re.fullmatch(r"cm(\d{2})([A-Z]{3})(\d{4})bhav\.csv\.zip", nm)
                    if m and m.group(2) in MONTHS:
                        d = "%s-%02d-%02d" % (m.group(3), MONTHS[m.group(2)], int(m.group(1)))
                else:
                    m = UDIFF_NAME_RE.match(nm)
                    if m:
                        d = "%s-%s-%s" % (m.group(4), m.group(5), m.group(6))
                if d:
                    a = Archive(kind, os.path.join(dirpath, nm), nm, d)
                    out.append(a)
    out.sort(key=Archive.key)
    return out


def select_file(files, kind, target_date):
    """exact date, else earliest on/after target; deterministic."""
    exact = [f for f in files if f.kind == kind and f.date == target_date]
    if exact:
        return exact[0], "exact"
    after = sorted((f for f in files if f.kind == kind and f.date >= target_date), key=Archive.key)
    return (after[0], "next_on_after") if after else (None, "not_found")


class Writer:
    def __init__(self, outdir):
        self.outdir = outdir
        os.makedirs(outdir, exist_ok=True)
        self.payloads = []

    def csv(self, fixture, name, header, rows):
        p = os.path.join(self.outdir, fixture + "__" + name)
        with open(p, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f, lineterminator="\n")
            if header is not None:
                w.writerow(header)
            w.writerows(rows)
        self.payloads.append(p)

    def raw(self, fixture, name, lines):
        p = os.path.join(self.outdir, fixture + "__" + name)
        with open(p, "w", newline="\n", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        self.payloads.append(p)

    def json(self, fixture, name, obj):
        p = os.path.join(self.outdir, fixture + "__" + name)
        with open(p, "w", encoding="utf-8") as f:
            json.dump(obj, f, indent=2, sort_keys=True)
            f.write("\n")
        self.payloads.append(p)


