        for d in window:
            for a in [x for x in files if x.date == d]:
                names, _idx = header_index(a.path)
                raw = open(a.path, "rb").read()
                with zipfile.ZipFile(a.path) as zf:
                    inner = zf.namelist()[0]
                    data = zf.read(inner)
