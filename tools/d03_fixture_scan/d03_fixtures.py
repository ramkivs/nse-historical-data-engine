def file_metrics(zip_path):
    names, idx = header_index(zip_path)
    ud = is_udiff_header(names)
    sym_c = idx.get("TckrSymb" if ud else "SYMBOL")
    ser_c = idx.get("SctySrs" if ud else "SERIES")
    isin_c = idx.get("ISIN")
    rows = blank_isin = nonblank_isin_rows = blank_sym = 0
    isin_set, sym_set, pair_set = set(), set(), set()
    pair_count = defaultdict(int)
    for i, r in iter_rows(zip_path):
        if i == 0:
            continue
        rows += 1
        sym = norm(get(r, idx, "TckrSymb" if ud else "SYMBOL"))
        ser = norm(get(r, idx, "SctySrs" if ud else "SERIES"))
        isin = norm(get(r, idx, "ISIN"))
        if isin == "":
            blank_isin += 1
        else:
            nonblank_isin_rows += 1
            isin_set.add(isin)
        if sym == "":
            blank_sym += 1
        else:
            sym_set.add(sym)
        pair_set.add((sym, ser))
        pair_count[(sym, ser)] += 1
    pair_dupes = sum(c - 1 for c in pair_count.values() if c > 1)
    return {
        "file": os.path.basename(zip_path), "format": "UDIFF" if ud else "LEGACY",
        "rows": rows,
        "blank_isin_rows": blank_isin,
        "distinct_nonblank_isin": len(isin_set),
        "nonblank_isin_rows": nonblank_isin_rows,
        "isins_extra_duplicate_rows": nonblank_isin_rows - len(isin_set),
        "blank_symbol_rows": blank_sym,
        "distinct_nonblank_symbol": len(sym_set),
        "distinct_symbol_series_pairs": len(pair_set),
        "symbol_series_duplicate_rows": pair_dupes,
    }


def fx_semdef(files, w, args):
    """Full-corpus per-file metric reconstruction on competing definitions, joined
    to the D01 inventory so D01's exact semantics are determined (not assumed).
    Selected D02 target dates are additionally flagged for presentation."""
    target_files = {}
    for kind, target in SEMDEF_TARGETS:
        a, sel = select_file(files, kind, target)
        if a is not None:
            target_files[a.name] = (target, sel)
    rows = []
    for a in sorted(files, key=lambda x: x.key()):
        m = file_metrics(a.path)
        m["is_d02_target"] = a.name in target_files
        m["requested_date"] = target_files[a.name][0] if a.name in target_files else ""
        m["selection"] = target_files[a.name][1] if a.name in target_files else ""
        if args.d01_inventory and os.path.isfile(args.d01_inventory):
            d01 = lookup_d01(args.d01_inventory, m["file"])
            if d01:
                m["d01_isin_count"] = d01["isin_count"]
                m["d01_symbol_count"] = d01["symbol_count"]
                m["d01_isin_eq_distinct_nonblank"] = (d01["isin_count"] == m["distinct_nonblank_isin"])
                m["d01_isin_eq_nonblank_rows"] = (d01["isin_count"] == m["nonblank_isin_rows"])
                m["d01_sym_eq_distinct_nonblank"] = (d01["symbol_count"] == m["distinct_nonblank_symbol"])
                m["d01_sym_eq_rows"] = (d01["symbol_count"] == m["rows"])
                m["discriminating_file"] = (m["isins_extra_duplicate_rows"] > 0) or (m["blank_isin_rows"] > 0)
        rows.append(m)
    keys = ["format", "date", "file", "header_fields", "rows", "blank_symbol_rows",
            "blank_isin_rows", "nonblank_isin_rows", "distinct_nonblank_isin",
            "isins_extra_duplicate_rows", "distinct_nonblank_symbol",
            "distinct_symbol_series_pairs", "symbol_series_duplicate_rows",
            "is_d02_target", "requested_date", "selection",
            "d01_isin_count", "d01_symbol_count",
            "d01_isin_eq_distinct_nonblank", "d01_isin_eq_nonblank_rows",
            "d01_sym_eq_distinct_nonblank", "d01_sym_eq_rows", "discriminating_file"]
    keys = [k for k in keys if any(k in r for r in rows)]
    w.csv("FIX-SEM-DEF-01", "metrics.csv", keys, [[r.get(k, "") for k in keys] for r in rows])
    discriminating = [r for r in rows if r.get("discriminating_file") and "d01_isin_count" in r]
    n_dist = sum(1 for r in discriminating if r.get("d01_isin_eq_distinct_nonblank"))
    n_rows = sum(1 for r in discriminating if r.get("d01_isin_eq_nonblank_rows"))
    verdict = ("D01 isin_count == DISTINCT-NONBLANK" if (discriminating and n_dist == len(discriminating) and n_rows != n_dist)
               else "D01 isin_count == NONBLANK-ROWS" if (discriminating and n_rows == len(discriminating) and n_rows != n_dist)
               else "AMBIGUOUS/MIXED - see per-file flags" if discriminating
               else "NO DISCRIMINATING FILES AVAILABLE")
    w.json("FIX-SEM-DEF-01", "d01_definition_verdict.json", {
        "discriminating_files": len(discriminating),
        "match_distinct_nonblank": n_dist,
        "match_nonblank_rows": n_rows,
        "verdict": verdict,
        "note": "Verdict derived only from files where the two definitions differ; non-discriminating files cannot distinguish them.",
    })
    w.json("FIX-SEM-DEF-01", "formula_definitions.json", {
        "formulas": {
            "rows": "count of data rows (header excluded)",
            "blank_isin_rows": "rows where ISIN is empty/whitespace-only",
            "distinct_nonblank_isin": "count of unique ISIN values (whitespace-stripped, uppercased, non-blank)",
            "nonblank_isin_rows": "count of rows with non-blank ISIN (duplicates included)",
            "isins_extra_duplicate_rows": "nonblank_isin_rows minus distinct_nonblank_isin",
            "distinct_nonblank_symbol": "count of unique non-blank symbols (stripped, uppercased)",
            "distinct_symbol_series_pairs": "count of unique (symbol,series) pairs",
            "symbol_series_duplicate_rows": "sum over pairs of (occurrences - 1)",
        },
        "reconstruction_rule": ("D01 isin_count is DISTINCT-NONBLANK iff, on a discriminating file "
                                "(duplicates or blanks present), d01_isin_count == distinct_nonblank_isin; "
                                "it is NONBLANK-ROWS iff == nonblank_isin_rows."),
        "note": "No D01 evidence is altered. This fixture only reconstructs and documents definitions.",
    })
    return rows


_D01_CACHE = {}


def lookup_d01(inv_path, file_name):
    if inv_path not in _D01_CACHE:
        with open(inv_path) as f:
            _D01_CACHE[inv_path] = {e["file_name"]: e for e in json.load(f)}
    return _D01_CACHE[inv_path].get(file_name)


