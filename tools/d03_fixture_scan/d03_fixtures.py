def fx_ud_census(files, w, args):
    udfs = [a for a in files if a.kind == "UDIFF"]
    groups = defaultdict(lambda: {"files": set(), "rows": 0, "blank_isin": 0, "isins": set(),
                                 "blank_fid": 0, "fids": set(), "fid_eq": 0, "fid_ne": 0,
                                 "blank_tk": 0, "tks": set(), "first": "9999-99-99", "last": "0000-00-00"})
    marg = {c: defaultdict(lambda: {"rows": 0, "files": set()}) for c in ("Sgmt", "Src", "FinInstrmTp", "SctySrs")}
    widths = defaultdict(int)
    sigs = defaultdict(int)
    for a in udfs:
        names, idx = header_index(a.path)
        widths[len(names)] += 1
        sigs[",".join(names)] += 1
        for i, r in iter_rows(a.path):
            if i == 0:
                continue
            sgmt, src, ftyp, srs = (get(r, idx, "Sgmt").strip(), get(r, idx, "Src").strip(),
                                     get(r, idx, "FinInstrmTp").strip(), norm(get(r, idx, "SctySrs")))
            key = (sgmt, src, ftyp, srs)
            g = groups[key]
            g["files"].add(a.name)
            g["rows"] += 1
            g["first"], g["last"] = min(g["first"], a.date), max(g["last"], a.date)
            isin, fid, tk = norm(get(r, idx, "ISIN")), norm(get(r, idx, "FinInstrmId")), norm(get(r, idx, "TckrSymb"))
            if isin == "":
                g["blank_isin"] += 1
            else:
                g["isins"].add(isin)
            if fid == "":
                g["blank_fid"] += 1
            else:
                g["fids"].add(fid)
            if fid and isin:
                g["fid_eq" if fid == isin else "fid_ne"] += 1
            if tk == "":
                g["blank_tk"] += 1
            else:
                g["tks"].add(tk)
            for colname, val in (("Sgmt", sgmt), ("Src", src), ("FinInstrmTp", ftyp), ("SctySrs", srs)):
                marg[colname][val]["rows"] += 1
                marg[colname][val]["files"].add(a.name)
    out = []
    for (sgmt, src, ftyp, srs), g in sorted(groups.items()):
        out.append([sgmt, src, ftyp, srs, len(g["files"]), g["rows"], len(g["isins"]), g["blank_isin"],
                    len(g["fids"]), g["blank_fid"], len(g["tks"]), g["blank_tk"], g["fid_eq"], g["fid_ne"],
                    g["first"], g["last"]])
    w.csv("FIX-UD-CENSUS-01", "groups.csv",
          ["Sgmt", "Src", "FinInstrmTp", "SctySrs", "archive_count", "row_count",
           "distinct_nonblank_isin", "blank_or_ws_isin_rows", "distinct_nonblank_finstrmid",
           "blank_or_ws_finstrmid_rows", "distinct_nonblank_tckrsymb", "blank_or_ws_tckrsymb_rows",
           "finstrmid_eq_isin_rows", "finstrmid_ne_isin_rows", "first_date", "last_date"], out)
    for colname in ("Sgmt", "Src", "FinInstrmTp", "SctySrs"):
        w.csv("FIX-UD-CENSUS-01", "marginal_%s.csv" % colname.lower(), [colname, "row_count", "archive_count"],
              [[v, m["rows"], len(m["files"])] for v, m in sorted(marg[colname].items())])
    w.json("FIX-UD-CENSUS-01", "header_width_check.json", {
        "expected_fields": UDIFF_HEADER_FIELDS,
        "observed_width_counts": {str(k): v for k, v in sorted(widths.items())},
        "distinct_header_signatures": len(sigs),
        "files_scanned": len(udfs),
        "verdict": ("VERIFIED: every UDiFF file has exactly the expected header width"
                    if set(widths) == {UDIFF_HEADER_FIELDS} else "MISMATCH — inspect header signatures"),
        "header_signatures": sorted(sigs),
    })


